def _html_to_text(html: str) -> str:
    soup = BeautifulSoup(html or "", "html.parser")
    return soup.get_text("\n", strip=True)

def _normalize_label(s: str) -> str:
    s = " ".join((s or "").strip().split())
    return (" ".join(s.split()[:3]).title()) if s else "Other"

def _tagify(prefix: str, label: str) -> str:
    safe = re.sub(r"[:/|]+", "-", label)
    safe = re.sub(r"\s+", " ", safe).strip()
    return f"{prefix}:{safe}"

def _get_existing_types(mi: MongoInterface, min_count: int = 1, limit: int = 40) -> List[str]:
    pipeline = [
        {"$match": {"TypeBucket": {"$exists": True, "$ne": ""}}},
        {"$group": {"_id": "$TypeBucket", "c": {"$sum": 1}}},
        {"$match": {"c": {"$gte": min_count}}},
        {"$sort": {"c": -1}},
        {"$limit": limit},
    ]
    return [doc["_id"] for doc in mi.db.PressRelease.aggregate(pipeline)]

def _extract_headings_from_html(html: str) -> List[str]:
    if not html: return []
    soup = BeautifulSoup(html, "html.parser")
    heads = []
    for tag in soup.find_all(re.compile(r"^h[1-4]$")):
        txt = tag.get_text(" ", strip=True)
        if txt: heads.append(txt)
    # also capture strong/paragraph lines that look like headings
    for tag in soup.find_all(["p", "strong", "b"]):
        txt = tag.get_text(" ", strip=True)
        if txt and _looks_like_heading(txt):
            heads.append(re.sub(r":\s*$", "", txt))
    return _dedup_preserve(heads)

def _extract_headings_from_text(text: str) -> List[str]:
    if not text: return []
    lines = [l.strip() for l in text.splitlines() if l.strip()]
    cand = []
    for l in lines:
        if _looks_like_heading(l):
            cand.append(re.sub(r":\s*$", "", l))
    return _dedup_preserve(cand)

def _looks_like_heading(line: str) -> bool:
    if len(line) > 90: return False
    words = line.split()
    if not (1 <= len(words) <= 10): return False
    if line.isupper() or line.istitle() or line.endswith(":"):
        return True
    if re.search(r"(about|disclaimer|outlook|strategy|highlights|overview|results|notes|risk|governance|financial)", line, re.I):
        return True
    return False

def _dedup_preserve(items: List[str]) -> List[str]:
    seen, out = set(), []
    for it in items:
        key = re.sub(r"\s+", " ", it.strip()).lower()
        if key and key not in seen:
            seen.add(key); out.append(it.strip())
    return out

class HistoricalStructureAnalyzerAgent(BaseAgent):
    """
    Analyzes historical MongoDB documents to extract successful structure patterns,
    tone guidelines, and phrase banks that have worked well for similar topics.
    This creates data-driven templates based on actual past performance.
    """
    def __init__(self, model: str = None):
        super().__init__()
        config = get_config()
        model_config = config.get_model_config('structure_generator.historical_analyzer')
        self.model = model or model_config['model']
        self.mi = MongoInterface()

    def _extract_historical_patterns(self, topic: str, type_bucket: str, lookback_days: int = 365) -> Dict[str, Any]:
        """Extract structure patterns from historical documents (both HTML and ProcessedContent)"""
        since = datetime.utcnow() - timedelta(days=lookback_days)
        
        # Find similar historical documents
        query = {
            "CreatedAt": {"$gte": since},
            "$or": [
                {"TypeBucket": type_bucket},
                {"Tags": _tagify("Bucket", type_bucket)}
            ]
        }
        
        # Get historical press releases with their structures
        historical_docs = list(self.mi.db.PressRelease.find(
            query,
            {"_id": 1, "TemplateHTML": 1, "Name": 1, "CreatedAt": 1, "TypeBucket": 1}
        ).sort("CreatedAt", -1).limit(15))
        
        # Extract structure patterns
        structure_patterns = {
            "section_frequency": {},
            "section_combinations": [],
            "tone_examples": [],
            "phrase_examples": [],
            "successful_structures": [],
            "html_sources": 0,
            "processed_content_sources": 0
        }
        
        for doc in historical_docs:
            pr_id = doc["_id"]
            headings = []
            
            # Extract headings from HTML (if available)
            html_content = doc.get("TemplateHTML", "")
            if html_content:
                html_headings = _extract_headings_from_html(html_content)
                headings.extend(html_headings)
                structure_patterns["html_sources"] += 1
            
            # Extract headings from ProcessedContent using Atlas Search
            try:
                # Get documents associated with this press release
                associated_docs = list(self.mi.db.Document.find(
                    {"PressReleaseId": pr_id}, 
                    {"_id": 1}
                ))
                
                for doc_ref in associated_docs:
                    doc_id = doc_ref["_id"]
                    
                    # Use Atlas Search to find relevant chunks for this document
                    search_query = f"DocumentId:{doc_id}"
                    
                    # Search using the default Atlas Search index
                    pipeline = [
                        {"$search": {
                            "index": "default",
                            "text": {"query": search_query, "path": "DocumentId"}
                        }},
                        {"$match": {"DocumentId": doc_id}},
                        {"$limit": 10},  # Limit to first 10 chunks
                        {"$project": {"Content": 1, "score": {"$meta": "searchScore"}}}
                    ]
                    
                    chunks = list(self.mi.db.ProcessedContent.aggregate(pipeline))
                    
                    if chunks:
                        # Combine chunk content to look for headings
                        combined_text = "\n".join([c.get("Content", "") for c in chunks])
                        if combined_text:
                            chunk_headings = _extract_headings_from_text(combined_text)
                            headings.extend(chunk_headings)
                            structure_patterns["processed_content_sources"] += 1
                        break  # Only count once per press release
            except Exception:
                # Fallback to direct chunk access if Atlas Search fails
                try:
                    for doc_ref in associated_docs:
                        chunks = self.mi.get_chunks_for_document(str(doc_ref["_id"]))
                        if chunks:
                            combined_text = "\n".join([c.get("Content", "") for c in chunks[:10]])
                            if combined_text:
                                chunk_headings = _extract_headings_from_text(combined_text)
                                headings.extend(chunk_headings)
                                structure_patterns["processed_content_sources"] += 1
                            break
                except Exception:
                    pass
            
            # Deduplicate and count section frequency
            unique_headings = _dedup_preserve(headings)
            for heading in unique_headings:
                structure_patterns["section_frequency"][heading] = structure_patterns["section_frequency"].get(heading, 0) + 1
            
            # Store successful structure combinations
            if unique_headings:
                structure_patterns["section_combinations"].append({
                    "doc_id": str(doc["_id"]),
                    "title": doc.get("Name", ""),
                    "sections": unique_headings,
                    "created_at": doc.get("CreatedAt"),
                    "type_bucket": doc.get("TypeBucket", ""),
                    "has_html": bool(html_content),
                    "has_processed_content": structure_patterns["processed_content_sources"] > 0
                })
        
        return structure_patterns

    def _extract_content_patterns(self, topic: str, type_bucket: str) -> Dict[str, Any]:
        """Extract tone and phrase patterns from document content (both HTML and ProcessedContent)"""
        since = datetime.utcnow() - timedelta(days=180)
        
        # Get document content for analysis
        query = {
            "CreatedAt": {"$gte": since},
            "$or": [
                {"TypeBucket": type_bucket},
                {"Tags": _tagify("Bucket", type_bucket)}
            ]
        }
        
        docs = list(self.mi.db.PressRelease.find(
            query,
            {"_id": 1, "TemplateHTML": 1, "Name": 1}
        ).limit(10))
        
        # Extract text content for tone/phrase analysis
        content_samples = []
        html_sources = 0
        processed_content_sources = 0
        
        for doc in docs:
            pr_id = doc["_id"]
            combined_content = ""
            content_sources = []
            
            # Extract from HTML (if available)
            html_content = doc.get("TemplateHTML", "")
            if html_content:
                html_text = _html_to_text(html_content)
                if html_text and len(html_text) > 100:
                    combined_content += html_text
                    content_sources.append("HTML")
                    html_sources += 1
            
            # Extract from ProcessedContent using Atlas Search
            try:
                # Get documents associated with this press release
                associated_docs = list(self.mi.db.Document.find(
                    {"PressReleaseId": pr_id}, 
                    {"_id": 1}
                ))
                
                for doc_ref in associated_docs:
                    doc_id = doc_ref["_id"]
                    
                    # Use Atlas Search to find relevant chunks for content analysis
                    search_query = f"DocumentId:{doc_id}"
                    
                    # Search using the default Atlas Search index
                    pipeline = [
                        {"$search": {
                            "index": "default",
                            "text": {"query": search_query, "path": "DocumentId"}
                        }},
                        {"$match": {"DocumentId": doc_id}},
                        {"$limit": 5},  # First 5 chunks for content analysis
                        {"$project": {"Content": 1, "score": {"$meta": "searchScore"}}}
                    ]
                    
                    chunks = list(self.mi.db.ProcessedContent.aggregate(pipeline))
                    
                    if chunks:
                        # Combine chunk content for analysis
                        chunk_text = "\n".join([c.get("Content", "") for c in chunks])
                        if chunk_text and len(chunk_text) > 100:
                            combined_content += "\n" + chunk_text
                            content_sources.append("ProcessedContent")
                            processed_content_sources += 1
                        break  # Only use first document's chunks
            except Exception:
                # Fallback to direct chunk access if Atlas Search fails
                try:
                    for doc_ref in associated_docs:
                        chunks = self.mi.get_chunks_for_document(str(doc_ref["_id"]))
                        if chunks:
                            chunk_text = "\n".join([c.get("Content", "") for c in chunks[:5]])
                            if chunk_text and len(chunk_text) > 100:
                                combined_content += "\n" + chunk_text
                                content_sources.append("ProcessedContent")
                                processed_content_sources += 1
                            break
                except Exception:
                    pass
            
            # Add to content samples if we have meaningful content
            if combined_content and len(combined_content) > 200:
                content_samples.append({
                    "title": doc.get("Name", ""),
                    "content": combined_content[:3000],  # First 3000 chars for analysis
                    "sources": content_sources
                })
        
        return {
            "content_samples": content_samples,
            "html_sources": html_sources,
            "processed_content_sources": processed_content_sources,
            "total_sources": html_sources + processed_content_sources
        }

    def _extract_semantic_patterns(self, topic: str, type_bucket: str) -> Dict[str, Any]:
        """Extract semantic patterns using vector search for similar content"""
        try:
            # Use vector search to find semantically similar content
            similar_chunks = self.mi.vector_search_filtered(
                query=topic,
                filter_docs=None,  # Search across all documents
                limit=20
            )
            
            # Extract headings from semantically similar content
            semantic_headings = []
            for chunk in similar_chunks:
                content = chunk.get("Content", "")
                if content:
                    headings = _extract_headings_from_text(content)
                    semantic_headings.extend(headings)
            
            # Count semantic heading frequency
            semantic_frequency = {}
            for heading in semantic_headings:
                semantic_frequency[heading] = semantic_frequency.get(heading, 0) + 1
            
            return {
                "semantic_headings": _dedup_preserve(semantic_headings),
                "semantic_frequency": semantic_frequency,
                "similar_chunks_found": len(similar_chunks)
            }
        except Exception:
            return {
                "semantic_headings": [],
                "semantic_frequency": {},
                "similar_chunks_found": 0
            }

