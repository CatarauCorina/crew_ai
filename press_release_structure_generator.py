def _get_recent_structure_variety(mi: MongoInterface, lookback_days: int = 90) -> List[str]:
    """Get recently used section names to avoid repetition."""
    since = datetime.utcnow() - timedelta(days=lookback_days)
    pipeline = [
        {"$match": {"CreatedAt": {"$gte": since}}},
        {"$project": {"TemplateHTML": 1}},
        {"$limit": 20}
    ]
    
    recent_sections = set()
    for pr in mi.db.PressRelease.aggregate(pipeline):
        headings = _extract_headings_from_html(pr.get("TemplateHTML", ""))
        recent_sections.update(headings)
    
    return list(recent_sections)

def _render_html_wireframe(sections: List[Dict[str, str]]) -> str:
    parts = ['<main class="press-release">']
    for s in sections:
        name = s.get("name","Section")
        parts.append(f'<section id="{re.sub(r"[^a-z0-9]+","-", name.lower()).strip("-")}">')
        parts.append(f'  <h2>{name}</h2>')
        parts.append(f'  <p>[data pending]</p>')
        parts.append('</section>')
    parts.append("</main>")
    return "\n".join(parts)

def _render_md_outline(sections: List[Dict[str, str]]) -> str:
    out = []
    for s in sections:
        out.append(f"## {s.get('name','Section')}\n\n[data pending]\n")
    return "\n".join(out)

